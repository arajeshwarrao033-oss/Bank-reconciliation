export function normalizeText(text: string): string {
  if (!text) return '';
  return text
    .toUpperCase()
    .replace(/^(ACH PAYMENT|POS DEBIT|POS CREDIT|DEBIT CARD|CREDIT CARD|CHECK #?|DIRECT DEP|WIRE TRANS|FT|EPN)\s*/i, '')
    .replace(/[^A-Z0-9\s]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

